import { test, expect, type Locator } from '@playwright/test'
import { autentifica, uiConfig } from './helpers'

const { projectId } = uiConfig()

async function isHitTarget(item: Locator) {
  return item.evaluate(el => {
    const rect = el.getBoundingClientRect()
    const hit = document.elementFromPoint(rect.left + rect.width / 2, rect.top + rect.height / 2)
    return !!hit && el.contains(hit)
  })
}

test('filtrele de utilizatori arată clar selecția', async ({ page }) => {
  await autentifica(page, 'admin')
  await page.goto('/admin/users')
  const group = page.getByRole('group', { name: 'Filtrează după starea contului' })
  const buttons = ['Activi', 'Dezactivați', 'Toți'].map(name => group.getByRole('button', { name, exact: true }))
  const colors = (button: Locator) => button.evaluate(el => {
    const css = getComputedStyle(el)
    return [css.backgroundColor, css.color, css.borderColor]
  })
  for (const selected of buttons) {
    await selected.click()
    await expect(selected).toHaveAttribute('aria-pressed', 'true')
    const other = buttons.find(button => button !== selected)!
    await expect(other).toHaveAttribute('aria-pressed', 'false')
    expect(await colors(selected)).not.toEqual(await colors(other))
  }
  const roles = page.getByRole('group', { name: 'Filtrează după rol' })
  const role = roles.getByRole('button', { name: 'Client', exact: true })
  await role.click()
  await expect(role).toHaveAttribute('aria-pressed', 'true')
  expect(await colors(role)).not.toEqual(await colors(roles.getByRole('button', { name: 'Toate', exact: true })))
})

test('fiecare buton așteaptă o secundă la hover, inclusiv după alt tooltip', async ({ page }) => {
  await autentifica(page, 'admin')
  await page.clock.install()
  await page.goto('/admin/users')
  const group = page.getByRole('group', { name: 'Filtrează după starea contului' })
  const first = group.getByRole('button', { name: 'Activi', exact: true })
  const second = group.getByRole('button', { name: 'Dezactivați', exact: true })
  await expect(first).toBeVisible()
  await page.clock.pauseAt(Date.now() + 60_000)
  await first.hover()
  await page.clock.runFor(1001)
  await expect(first).toHaveAttribute('data-tooltip-state', 'open')
  await second.hover()
  await page.clock.runFor(999)
  await expect(page.locator('#sg-tooltip')).toHaveCount(0)
  await page.clock.runFor(2)
  await expect(second).toHaveAttribute('data-tooltip-state', 'open')
  const tip = page.locator('#sg-tooltip')
  const box = await tip.boundingBox()
  expect(box).not.toBeNull()
  await page.mouse.move(box!.x + box!.width / 2, box!.y + box!.height / 2, { steps: 4 })
  await page.clock.runFor(200)
  await expect(tip).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(tip).toHaveCount(0)
  await second.focus()
  await page.keyboard.press('Shift+Tab')
  await expect(first).toBeFocused()
  await page.clock.runFor(1)
  await expect(first).toHaveAttribute('data-tooltip-state', 'open')
  await page.keyboard.press('Escape')
  await expect(tip).toHaveCount(0)
})

for (const width of [390, 1440]) {
  test(`meniurile fazei și activității sunt accesibile la ${width}px`, async ({ page }) => {
    test.skip(!projectId, 'E2E_PROJECT_ID lipsește')
    await page.setViewportSize({ width, height: 844 })
    await autentifica(page, 'admin')
    await page.goto(`/projects/${projectId}`)
    if (width < 768) await page.getByRole('button', { name: 'Toate fazele: reordonare, activități, echipă' }).click()
    const sidebar = page.locator('aside').filter({ has: page.getByText('Toate fazele', { exact: true }) })
    const phase = sidebar.getByRole('button', { name: /^Acțiuni pentru faza / }).first()
    await phase.hover()
    await phase.click()
    const rename = page.getByRole('menuitem', { name: 'Redenumește' })
    await expect(rename).toBeVisible()
    expect(await isHitTarget(rename)).toBe(true)
    await page.keyboard.press('Escape')
    await expect(phase).toBeFocused()
    await phase.click()
    await page.getByRole('menuitem', { name: 'Duplică' }).click()
    const cancel = page.getByRole('dialog').getByRole('button', { name: 'Anulează' })
    await expect(cancel).toBeVisible()
    expect(await isHitTarget(cancel)).toBe(true)
    await cancel.click()
    await phase.click()
    await rename.click()
    await expect(sidebar.getByPlaceholder('Nume fază...')).toBeVisible()
    await sidebar.getByRole('button', { name: 'Renunță la redenumire' }).click()
    const expand = sidebar.getByRole('button', { name: 'Extinde faza' }).first()
    if (await expand.count()) await expand.click()
    const activity = sidebar.getByRole('button', { name: /^Acțiuni pentru activitatea / }).first()
    await activity.hover()
    await activity.click()
    await expect(rename).toBeVisible()
    expect(await isHitTarget(rename)).toBe(true)
    await rename.click()
    await expect(sidebar.getByPlaceholder('Nume activitate...')).toBeVisible()
    await sidebar.getByRole('button', { name: 'Renunță la redenumire' }).click()
    await activity.hover()
    await activity.click()
    await page.mouse.click(width - 2, 2)
    await expect(page.getByRole('menu')).toHaveCount(0)
  })
}
